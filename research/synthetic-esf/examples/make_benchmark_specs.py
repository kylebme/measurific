"""Rebuild the checked-in benchmark/suite examples and synthetic tabulated PSF.

No empirical data is fabricated: the tabulated kernel is explicitly synthetic.
"""
from pathlib import Path
import json
import numpy as np

folder = Path(__file__).resolve().parent


def save(name, value):
    (folder/name).write_text(json.dumps(value, indent=2)+'\n')


nodes = []
for y in [-1, 0, 1]:
    for x in [-1, 0, 1]:
        r2 = x*x+y*y
        nodes.append(dict(sigma_px=0.48+0.15*r2, sigma_y_px=0.48+0.06*r2,
                          angle_deg=float(np.rad2deg(np.arctan2(y, x))) if r2 else 0,
                          tail_offset_px=[0.5*x, 0.5*y], tail_weight=0.04+0.03*r2))

calibration_positions = [[x, y] for y in [40, 96, 152] for x in [56, 128, 200]]
held_positions = [[92, 68], [164, 124]]
groups = []


def group(name, split, shapes, **kwargs):
    groups.append(dict(id=name, split=split, shapes=shapes,
                       placements_px=calibration_positions if split == 'calibration' else held_positions,
                       phases_px=[[0.19, 0.37]] if split == 'calibration' else [[0.61, 0.83]], roi_size=[32, 32], **kwargs))


for name, radius in [('cal_pin_small', 0.060), ('cal_pin_large', 0.085)]:
    group(name, 'calibration', [dict(kind='cylinder', axis='z', radius_mm=radius, length_mm=0.03)], tags=['pin', 'field_calibration'])
for name, size in [('cal_block_small', [0.12, 0.15, 0.03]), ('cal_block_large', [0.17, 0.13, 0.03])]:
    group(name, 'calibration', [dict(kind='box', size_mm=size)], tags=['block', 'field_calibration'])
group('test_pin_dimension', 'held_out', [dict(kind='cylinder', axis='z', radius_mm=0.073, length_mm=0.03)], tags=['unseen_dimension', 'unseen_position', 'matched_optics'])
group('test_rotated_block', 'held_out', [dict(kind='box', size_mm=[0.146, 0.178, 0.03], angle_deg=17)], tags=['unseen_dimension', 'unseen_orientation', 'matched_optics'])
group('test_sphere_diffuse', 'held_out', [dict(kind='sphere', radius_mm=0.081, center_mm=[0, 0, 0.12])], illumination=dict(kind='diffuse', samples=64), tags=['unseen_geometry', 'diffuse', 'height'])
group('test_horizontal_pin', 'held_out', [dict(kind='cylinder', axis='y', radius_mm=0.068, length_mm=0.17, center_mm=[0, 0, 0.18], angle_deg=13)], illumination=dict(kind='diffuse', samples=64), tags=['diffuse', 'height', 'unseen_orientation'])
group('test_nearby_edges', 'held_out', [dict(kind='box', size_mm=[0.061, 0.18, 0.05], center_mm=[x, 0, 0]) for x in [-0.04, 0.04]], tags=['nearby_edges', 'narrow_gap', 'model_mismatch'])
group('test_corner_asymmetric', 'held_out', [dict(kind='box', size_mm=[0.155, 0.155, 0.04], angle_deg=45)], optics=dict(psf='mixture', field_grid=[1, 1], field_nodes=[], sigma_px=0.5, tail_weight=0.22, tail_offset_px=[1.2, 0.7], tail_sigma_px=1.4, support_px=6), tags=['corners', 'asymmetric', 'model_mismatch'])
group('test_airy', 'held_out', [dict(kind='sphere', radius_mm=0.076)], optics=dict(psf='airy', field_grid=[1, 1], field_nodes=[], object_na=0.08, support_px=8), tags=['diffraction_proxy', 'model_mismatch'])
x, y = np.meshgrid(np.arange(-50, 51)*0.001, np.arange(-50, 51)*0.001)
kernel = np.exp(-np.sqrt((x/0.004)**2+(y/0.006)**2)) + 0.20*np.exp(-np.sqrt(((x-0.011)/0.010)**2+((y+0.003)/0.003)**2))
np.save(folder/'synthetic_tabulated_psf.npy', kernel/kernel.sum())
group('test_tabulated_kernel', 'held_out', [dict(kind='cylinder', axis='z', radius_mm=0.091, length_mm=0.031)],
      optics=dict(psf='measured', field_grid=[1, 1], field_nodes=[], measured_path='synthetic_tabulated_psf.npy', measured_pitch_um=1, support_px=6),
      kernel_provenance=dict(kind='synthetic', description='Two displaced anisotropic radial-exponential components; generated by make_benchmark_specs.py, not measured from hardware', pre_pixel=True, registered_origin=True),
      tags=['tabulated_kernel', 'model_mismatch'])

save('calibration_benchmark.json', dict(description='Artifact-grouped benchmark: train on pins/blocks over a 3x3 field grid; hold out dimensions, positions, geometries and optical conditions. Preview sampling; qualify representative patches with validation-suite.',
     seed=2026, exposures_ms=[0.5, 1.0], repeat_captures=2,
     config=dict(camera=dict(width=256, height=192, pixel_pitch_um=10, magnification=1, distortion_radial=[0.007, -0.001, 0], distortion_tangential=[0.0005, -0.0003]),
                 illumination=dict(kind='collimated'), optics=dict(psf='mixture', object_na=0.025, support_px=4, field_grid=[3, 3], field_nodes=nodes),
                 sampling=dict(supersample=16, tile_px=32)), groups=groups))

suite_config = dict(camera=dict(width=48, height=40, pixel_pitch_um=10, magnification=1), illumination=dict(kind='diffuse', samples=128),
                    optics=dict(psf='gaussian', object_na=0.025, sigma_px=0.6, support_px=4), sampling=dict(supersample=64, tile_px=16))
cases = [
    dict(id='sphere_diffuse_phase_height', shapes=[dict(kind='sphere', radius_mm=0.07)], roi=[25, 14, 12, 12],
         phases_px=[[0.13, 0.29], [0.61, 0.83]], z_offsets_mm=[-0.06, 0.10], source_seeds=[17], levels=[16, 32, 64], angular_levels=[32, 128], contour_count=512),
    dict(id='horizontal_pin_diffuse_seeds', shapes=[dict(kind='cylinder', axis='y', radius_mm=0.07, length_mm=0.4, angle_deg=11)], roi=[25, 14, 12, 12],
         phases_px=[[0.37, 0.19]], z_offsets_mm=[0.04, 0.18], source_seeds=[3, 19], levels=[16, 32, 64], angular_levels=[32, 128], contour_count=512),
    dict(id='mesh_tessellation', shapes=[dict(kind='cylinder', axis='z', radius_mm=0.07, length_mm=0.03)], roi=[25, 14, 12, 12], phases_px=[[0.29, 0.41]],
         config=dict(illumination=dict(kind='collimated')), levels=[16, 32, 64], mesh_sections=[16, 32, 64, 128], contour_count=512),
    dict(id='field_distortion_asymmetry', shapes=[dict(kind='sphere', radius_mm=0.07, center_mm=[0.08, 0.03, 0])], roi=[32, 17, 12, 12],
         config=dict(camera=dict(distortion_radial=[0.008, 0, 0], distortion_tangential=[0.001, -0.0005]),
                     illumination=dict(kind='collimated'), optics=dict(psf='mixture', field_grid=[3, 3], field_nodes=nodes, support_px=5)),
         levels=[16, 32, 64], support_levels=[4, 6], contour_count=512),
]
save('convergence_suite.json', dict(description='Curved/diffuse phase-height studies, independent source seeds, analytic-vs-mesh tolerance, field distortion/asymmetry. Failures are retained; increase resolution for failing cases.', tolerance_px=0.01, config=suite_config, cases=cases))
print('Wrote calibration_benchmark.json, convergence_suite.json and synthetic_tabulated_psf.npy')
